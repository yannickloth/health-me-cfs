import java.nio.file.*;
import java.util.*;
import java.util.regex.*;
import java.util.stream.*;

/// GeneratePathwayTable — build a reader-facing Typst table of pathway coverage
/// from ops/plans/pathway-registry.md.
///
/// Reads the registry Markdown, walks each "## N. <Family> (location)" section,
/// counts the status column (mapped / partial / in-paper / evidence-empty /
/// not-assessed) across that section's table rows, and emits a condensed
/// Typst #table with one row per family. Used as a pre-typst-compile build step
/// so the published table can never drift from the registry.
///
/// Usage: java --source 25 GeneratePathwayTable.java <registry.md> <output.typ>
public class GeneratePathwayTable {

    private static final Pattern FAMILY = Pattern.compile("^## (\\d+)\\. (.+?)\\s*$");
    private static final Pattern ROW = Pattern.compile("^\\|\\s+([^|]+)\\s+\\|\\s+[^|]+\\s+\\|\\s+([^|]+)\\s+\\|");
    private static final List<String> STATUSES =
        List.of("mapped", "partial", "in-paper", "evidence-empty", "not-assessed");

    record Family(int num, String title, Map<String, Long> counts) {}

    public static void main(String[] args) throws Exception {
        if (args.length < 2) {
            System.err.println("usage: GeneratePathwayTable <registry.md> <output.typ>");
            System.exit(2);
        }
        var lines = Files.readAllLines(Path.of(args[0]));
        var families = new ArrayList<Family>();
        Family current = null;

        for (var line : lines) {
            var m = FAMILY.matcher(line);
            if (m.matches()) {
                if (current != null) families.add(current);
                var c = new LinkedHashMap<String, Long>();
                STATUSES.forEach(s -> c.put(s, 0L));
                current = new Family(Integer.parseInt(m.group(1)), m.group(2).trim(), c);
                continue;
            }
            if (current == null) continue;
            var r = ROW.matcher(line);
            if (!r.find()) continue;
            var status = r.group(2).trim().toLowerCase();
            var cc = current.counts();
            cc.computeIfPresent(status, (k, v) -> v + 1);
        }
        if (current != null) families.add(current);

        var sb = new StringBuilder();
        sb.append("// Generated by GeneratePathwayTable.java from ops/plans/pathway-registry.md.\n");
        sb.append("// Do not edit by hand. Status legend: mapped (integrated, >=2 sources), partial,\n");
        sb.append("// in-paper (minor mention), evidence-empty (searched, no qualifying), not-assessed.\n");
        sb.append("#table(\n  columns: (1fr, 1fr, 1fr, 1fr, 1fr, 1fr),\n");
        sb.append("  [*Pathway family*], [*Mapped*], [*Partial*], [*In paper*], [*Evidence-empty*], [*Not assessed*],\n");
        for (var f : families) {
            sb.append("  [").append(f.num()).append(". ").append(f.title()).append("], ");
            sb.append("[ ").append(f.counts.get("mapped")).append(" ], ");
            sb.append("[ ").append(f.counts.get("partial")).append(" ], ");
            sb.append("[ ").append(f.counts.get("in-paper")).append(" ], ");
            sb.append("[ ").append(f.counts.get("evidence-empty")).append(" ], ");
            sb.append("[ ").append(f.counts.get("not-assessed")).append(" ],\n");
        }
        sb.append(")\n");

        Files.writeString(Path.of(args[1]), sb.toString());
        System.out.println("Generated " + args[1] + " (" + families.size() + " families)");
    }
}
