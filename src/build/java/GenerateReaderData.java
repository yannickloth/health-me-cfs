import java.nio.file.*;
import java.util.*;
import java.util.regex.*;

/// GenerateReaderData — build a reader-facing Typst data file of per-chapter
/// navigation metadata (reading time + per-reader-group depth) used by the
/// Reading Guide matrix.
///
/// For each chapter under part1-5, this:
///   1. counts words across the chapter's Typst sources (stripping markup,
///      comments, code, and includes) and derives a reading time at ~238 wpm;
///   2. parses the chapter's #roadmap box and classifies each reader group
///      (patients / caregivers / clinicians / researchers) as Essential,
///      Recommended, Optional, Skip, or — (no guidance) from the roadmap's
///      explicit depth language.
///
/// Emits a Typst file of per-part #figure(table(...)) blocks the Reading Guide
/// includes, with a clickable `@ch:` link per chapter, reading time, and a
/// depth cell per reader group. Classification is conservative and
/// source-derived: only explicit depth keywords downgrade a rating; an
/// unmentioned group is left as "—"; a group the roadmap tells to read is
/// Recommended (not Essential). Do not edit the output by hand.
///
/// Usage: java --source 25 GenerateReaderData.java <mecfsRoot> <partChaptersJson> <output.typ>
public class GenerateReaderData {

    private static final int WPM = 238;

    // Chapter-label regex, e.g. "<ch:introduction>".
    private static final Pattern CH_LABEL = Pattern.compile("<ch:([a-z0-9-]+)>");
    // Chapter heading, e.g. "= Introduction to ME/CFS".
    private static final Pattern HEADING = Pattern.compile("^=\\s+(.+?)\\s*$", Pattern.MULTILINE);
    // Reader-group markers inside a roadmap box.
    private static final Pattern READER = Pattern.compile(
        "\\*For\\s+(patients|caregivers|clinicians|researchers)\\*\\s*:\\s*(.*?)(?=\\n\\s*\\*For\\s+(?:patients|caregivers|clinicians|researchers)\\*|\\Z)",
        Pattern.DOTALL);

    private static final List<String> READER_KEYS =
        List.of("patients", "caregivers", "clinicians", "researchers");

    record ReaderData(String label, String title, int minutes, Map<String, String> readers) {}

    public static void main(String[] args) throws Exception {
        if (args.length < 3) {
            System.err.println("usage: GenerateReaderData <mecfsRoot> <partChaptersJson> <output.typ>");
            System.exit(2);
        }
        var root = Path.of(args[0]).normalize();
        var partChaptersJson = Path.of(args[1]).normalize();
        var output = Path.of(args[2]).normalize();

        // Canonical per-part chapter directories come from part-chapters.json
        // (the same single source GenerateSidebar uses), so sub-chapter/section
        // directories that share a "chNN-" prefix but are not top-level chapters
        // (e.g. ch25-brain-clearance-supplements) are never misread as chapters.
        var canonicalChapters = readPartChapters(partChaptersJson);

        var all = new ArrayList<Map<String, Object>>();
        int totalWords = 0;
        for (var entry : canonicalChapters.entrySet()) {
            var part = entry.getKey();
            var partDir = root.resolve(partDirName(part));
            if (!Files.isDirectory(partDir)) continue;
            var chapters = new ArrayList<ReaderData>();
            for (var chDirName : entry.getValue()) {
                var chDir = partDir.resolve(chDirName);
                if (!Files.isDirectory(chDir)) continue;
                var rd = processChapter(chDir);
                if (rd != null) {
                    chapters.add(rd);
                    totalWords += wordCount(chDir);
                }
            }
            if (chapters.isEmpty()) continue;
            var partEntry = new LinkedHashMap<String, Object>();
            partEntry.put("title", humanizePart(part));
            partEntry.put("chapters", chapters);
            all.add(partEntry);
        }

        var sb = new StringBuilder();
        sb.append("// Generated by GenerateReaderData.java from chapter sources.\n");
        sb.append("// Do not edit by hand. Depth legend (per reader group):\n");
        sb.append("//   E = Essential, R = Recommended, O = Optional, S = Skip, — = no guidance.\n");
        sb.append("// Reading time is words / ").append(WPM).append(" wpm. Conservative classifier:\n");
        sb.append("// only explicit skip/skim/optional language downgrades a rating.\n");
        sb.append("#import \"tables.typ\": booktabs-stroke, table-inset\n\n");
        for (var i = 0; i < all.size(); i++) {
            @SuppressWarnings("unchecked")
            var part = (Map<String, Object>) all.get(i);
            sb.append("#figure(\n  table(\n");
            sb.append("    columns: (2.2fr, 0.5fr, 0.7fr, 0.7fr, 0.9fr, 0.9fr),\n");
            sb.append("    inset: table-inset,\n");
            sb.append("    stroke: booktabs-stroke(").append(
                ((List<?>) part.get("chapters")).size() + 1).append("),\n");
            sb.append("    [*Chapter*], [*Time*], [*Patient*], [*Caregiver*], [*Clinician*], [*Researcher*],\n");
            @SuppressWarnings("unchecked")
            var chs = (List<ReaderData>) part.get("chapters");
            for (var c : chs) {
                sb.append("    [@ch:").append(c.label()).append("], ");
                sb.append("[").append(c.minutes()).append(" min], ");
                for (var k : READER_KEYS) {
                    sb.append("[").append(depthWord(c.readers().get(k))).append("], ");
                }
                sb.append("\n");
            }
            sb.append("  ),\n");
            sb.append("  caption: [Chapter-level reading routes and estimated time — ")
                .append(part.get("title")).append("],\n");
            sb.append(")\n\n");
        }

        Files.writeString(output, sb.toString());
        System.out.println("Generated " + output + " (" + all.size()
            + " parts, ~" + (totalWords / WPM) + " total min, " + totalWords + " words)");
    }

    // Parse part-chapters.json -> LinkedHashMap<partId, List<chapterDir>> in
    // canonical document order. Chapter dir name is the penultimate path segment
    // of each chapter href (e.g. "part3-treatment/ch22-mechanism-treatment-map/
    // index.html" -> "ch22-mechanism-treatment-map").
    private static Map<String, List<String>> readPartChapters(Path jsonPath) throws Exception {
        var out = new LinkedHashMap<String, List<String>>();
        var text = Files.readString(jsonPath);
        var partPat = Pattern.compile("\"id\"\\s*:\\s*\"(part[1-5])\"");
        var m = partPat.matcher(text);
        while (m.find()) {
            var part = m.group(1);
            var dirs = new ArrayList<String>();
            var nextM = partPat.matcher(text);
            var end = nextM.find(m.end()) ? nextM.start() : text.length();
            var chunk = text.substring(m.end(), end);
            var hrefPat = Pattern.compile("\"href\"\\s*:\\s*\"[^\"]*/([^/]+)/index\\.html\"");
            var hm = hrefPat.matcher(chunk);
            while (hm.find()) dirs.add(hm.group(1));
            if (!dirs.isEmpty()) out.put(part, dirs);
        }
        return out;
    }

    private static ReaderData processChapter(Path chDir) throws Exception {
        var files = new ArrayList<Path>();
        try (var stream = Files.walk(chDir)) {
            stream.filter(Files::isRegularFile)
                .filter(p -> p.toString().endsWith(".typ"))
                .sorted().forEach(files::add);
        }
        if (files.isEmpty()) return null;

        // Label + title from the chapter's landing file (first file with a heading).
        String label = null;
        String title = null;
        String roadmap = null;
        for (var f : files) {
            var text = Files.readString(f);
            if (label == null) {
                var lm = CH_LABEL.matcher(text);
                if (lm.find()) label = lm.group(1);
            }
            if (title == null) {
                var hm = HEADING.matcher(text);
                if (hm.find()) title = cleanTitle(hm.group(1));
            }
            if (roadmap == null && text.contains("#roadmap")) {
                roadmap = extractRoadmap(text);
            }
        }
        if (label == null) label = chDir.getFileName().toString();
        if (title == null) title = humanize(chDir.getFileName().toString());
        if (roadmap == null) roadmap = "";

        int minutes = Math.max(1, Math.round((float) wordCount(chDir) / WPM));
        return new ReaderData(label, title, minutes, classifyReaders(roadmap));
    }

    private static Map<String, String> classifyReaders(String roadmap) {
        var out = new LinkedHashMap<String, String>();
        for (var k : READER_KEYS) out.put(k, "—");
        if (roadmap.isEmpty()) return out;
        var m = READER.matcher(roadmap);
        while (m.find()) {
            var group = m.group(1).toLowerCase();
            var body = m.group(2).toLowerCase();
            out.put(group, classify(body));
        }
        return out;
    }

    private static String classify(String body) {
        // Chapter-level qualifiers dominate: a group the roadmap calls optional /
        // negligible / skippable is never marked higher than Optional.
        if (body.contains("optional background")
            || body.contains("minimal direct use")
            || body.contains("no direct use")
            || body.contains("can be skipped")
            || body.contains("this chapter is optional")
            || body.contains("this chapter is speculative and can be skipped")) {
            return "O";
        }
        // Reading (even partially) makes the chapter Recommended for that group.
        if (body.contains("read")) return "R";
        // Skimming only (no "read") is Optional.
        if (body.contains("skim") || body.contains("optional")) return "O";
        return "—";
    }

    private static String extractRoadmap(String text) {
        var m = Pattern.compile("#roadmap\\([^)]*\\)\\[(.*?)\\]\\s*(?:<[^>]+>)?\\s*$",
            Pattern.DOTALL).matcher(text);
        if (m.find()) return m.group(1);
        // Fallback: up to the next blank line after #roadmap's opening bracket.
        var start = text.indexOf("#roadmap");
        if (start < 0) return "";
        var open = text.indexOf("[", start);
        if (open < 0) return "";
        return text.substring(open);
    }

    private static int wordCount(Path chDir) throws Exception {
        int words = 0;
        try (var stream = Files.walk(chDir)) {
            var files = stream.filter(Files::isRegularFile)
                .filter(p -> p.toString().endsWith(".typ")).toList();
            for (var f : files) {
                var text = Files.readString(f);
                text = text.replaceAll("#include\\s+\"[^\"]+\"", " ");
                text = text.replaceAll("//[^\\n]*", " ");
                text = text.replaceAll("#[a-zA-Z][\\w-]*\\([^)]*\\)", " ");
                text = text.replaceAll("#[a-zA-Z][\\w-]*", " ");
                text = text.replaceAll("\\[[^\\]]*\\]", " ");
                text = text.replaceAll("<[^>]*>", " ");
                text = text.replaceAll("[@$*/_=\\-()\\.,;:!?<>]", " ");
                words += text.trim().split("\\s+").length;
            }
        }
        return words;
    }

    private static String cleanTitle(String raw) {
        // Strip trailing structure labels like " <ch:...>".
        return raw.replaceAll("\\s*<[^>]+>\\s*$", "").strip();
    }

    private static String humanizePart(String part) {
        return switch (part) {
            case "part1" -> "Part I — Clinical Presentation";
            case "part2" -> "Part II — Pathophysiology";
            case "part3" -> "Part III — Treatment and Management";
            case "part4" -> "Part IV — Research and Evidence";
            case "part5" -> "Part V — Mathematical Modeling";
            default -> part;
        };
    }

    private static String partDirName(String part) {
        return switch (part) {
            case "part1" -> "part1-clinical";
            case "part2" -> "part2-pathophysiology";
            case "part3" -> "part3-treatment";
            case "part4" -> "part4-research";
            case "part5" -> "part5-modeling";
            default -> part;
        };
    }

    private static String humanize(String dir) {
        return dir.replaceFirst("^ch\\d+-", "").replaceAll("[-_]+", " ").strip();
    }

    // Depth code -> human word for the table cell.
    private static String depthWord(String code) {
        return switch (code) {
            case "E" -> "Essential";
            case "R" -> "Recommended";
            case "O" -> "Optional";
            case "S" -> "Skip";
            default -> "—";
        };
    }
}
